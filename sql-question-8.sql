-- retrieve the total revenue generated by each product 

select p.product_name,sum(product_price*Quantity)
from ezecash.products p ,ezecash.Orders o
where p.product_id=o.ProductID
group by  p.product_name
order by substr(PRODUCT_NAME,instr(PRODUCT_NAME,' '),2);

--find products that have not been ordered at all 
select  p.product_id,p.product_name
from ezecash.products p ,ezecash.Orders o
where p.product_id=o.ProductID(+)
and o.ProductID is null 
