CREATE TABLE ezecash.products (
    product_id number PRIMARY KEY,
    product_name VARCHAR2(100),
    product_price number
);

CREATE TABLE ezecash.Orders  (
    OrderID NUMBER PRIMARY KEY,
    ProductID NUMBER,
    Quantity NUMBER,
    OrderDate DATE,
    FOREIGN KEY (ProductID) REFERENCES ezecash.Products(product_id)
);


